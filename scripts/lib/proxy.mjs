// Builds the server reverse proxy from the registry (ADR-0012, #251): one nginx takes 443 for every
// active app and forwards to 127.0.0.1:<ports.web>, with one Let's Encrypt wildcard certificate that
// certbot renews through Route 53 DNS validation. The output is copied to PROXY_DIR on the server.
import { serviceHost } from './registry.mjs';

export const PROXY_DIR = '/opt/project-standards/proxy';
export const SHARED_ENV = '/opt/project-standards/.env';

const HEADER = '# Generated by scripts/proxy-config.mjs in sirloinbh/project-standards from the registry. Do not edit it on the server; regenerate and copy it (docs/runbooks/proxy.md).';

/** Active apps with their address and web port, in slot order. */
export function proxyApps(data, domain) {
  return data.projects.projects
    .filter((p) => p.status === 'active')
    .sort((a, b) => a.slot - b.slot)
    .map((p) => {
      // The one wildcard certificate covers only names directly under the root domain.
      if (p.service.domain && p.service.domain !== domain) throw new Error(`${p.name}: service.domain "${p.service.domain}" is not covered by the *.${domain} certificate`);
      return { name: p.name, slot: p.slot, host: serviceHost(p, { rootDomain: domain }), port: p.ports.web };
    });
}

function nginxConf(domain, apps) {
  const server = (app) => `# ${app.name} (slot ${app.slot})
server {
  listen 443 ssl;
  http2 on;
  server_name ${app.host};
  # The app's own nginx sends nosniff and Referrer-Policy; HSTS belongs to the HTTPS layer.
  add_header Strict-Transport-Security "max-age=31536000" always;

  location / {
    proxy_pass http://127.0.0.1:${app.port};
    proxy_set_header Host $host;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto https;
  }
}`;
  return `${HEADER}
# Only allowed IPs reach 80 and 443 (Lightsail firewall, ADR-0012), so nginx has no allow list.

ssl_certificate /etc/letsencrypt/live/${domain}/fullchain.pem;
ssl_certificate_key /etc/letsencrypt/live/${domain}/privkey.pem;
ssl_protocols TLSv1.2 TLSv1.3;
ssl_session_cache shared:SSL:10m;
ssl_session_timeout 1d;
server_tokens off;

# A name that is not an app gets nothing: no redirect, no certificate.
server {
  listen 80 default_server;
  return 444;
}
server {
  listen 443 ssl default_server;
  ssl_reject_handshake on;
}

server {
  listen 80;
  server_name ${apps.map((a) => a.host).join(' ')};
  return 301 https://$host$request_uri;
}

${apps.map(server).join('\n\n')}
`;
}

function compose(versions) {
  return `${HEADER}
name: proxy
services:
  nginx:
    image: ${versions.images.nginx}
    # The apps publish their web ports on the host, so the proxy shares the host network.
    network_mode: host
    restart: unless-stopped
    volumes:
      - ./nginx/apps.conf:/etc/nginx/conf.d/default.conf:ro
      - ./letsencrypt:/etc/letsencrypt:ro
  certbot:
    image: ${versions.images.certbot}
    # Runs only from cert.sh, never with \`up\`.
    profiles: [certbot]
    # cert.sh exports these from CERTBOT_AWS_* in the shared server file.
    environment:
      - AWS_ACCESS_KEY_ID
      - AWS_SECRET_ACCESS_KEY
    volumes:
      - ./letsencrypt:/etc/letsencrypt
`;
}

function certScript(domain) {
  return `#!/usr/bin/env bash
${HEADER}
# Usage (as root):
#   cert.sh issue     first certificate for ${domain} and *.${domain}
#   cert.sh renew     renew when due, reload nginx, ping healthchecks.io (the timer runs this)
#   cert.sh dry-run   test renewal against the Let's Encrypt staging server
#   cert.sh reload    check and reload the nginx config after copying a new apps.conf
#   cert.sh install   install and start the twice-daily renewal timer
set -euo pipefail

dir=$(cd "$(dirname "$0")" && pwd)
shared_env=\${STANDARDS_ENV_FILE:-${SHARED_ENV}}
cd "$dir"

read_key() {
  [ -r "$shared_env" ] && sed -n "s/^$1=//p" "$shared_env" | tail -n 1 | tr -d "\\"'\\r"
}

certbot() {
  AWS_ACCESS_KEY_ID=$(read_key CERTBOT_AWS_ACCESS_KEY_ID || true)
  AWS_SECRET_ACCESS_KEY=$(read_key CERTBOT_AWS_SECRET_ACCESS_KEY || true)
  if [ -z "$AWS_ACCESS_KEY_ID" ] || [ -z "$AWS_SECRET_ACCESS_KEY" ]; then
    echo "CERTBOT_AWS_ACCESS_KEY_ID or CERTBOT_AWS_SECRET_ACCESS_KEY is missing in $shared_env" >&2
    return 1
  fi
  export AWS_ACCESS_KEY_ID AWS_SECRET_ACCESS_KEY
  docker compose run --rm certbot "$@"
}

reload() {
  docker compose exec -T nginx nginx -t
  docker compose exec -T nginx nginx -s reload
}

# Sends ok or fail to HEALTHCHECK_URL_CERT. A missing key or a failed ping never fails the caller.
ping() {
  local url
  url=$(read_key HEALTHCHECK_URL_CERT || true)
  [ -n "$url" ] || return 0
  [ "$1" = ok ] || url="$url/fail"
  printf '%s' "$2" | head -c 10000 | curl -fsS -m 10 --retry 3 -o /dev/null --data-binary @- "$url" || echo "healthchecks.io ping failed" >&2
}

case "\${1:-}" in
  issue)
    certbot certonly --dns-route53 --non-interactive --agree-tos --register-unsafely-without-email \\
      --cert-name ${domain} -d ${domain} -d '*.${domain}'
    ;;
  renew)
    if out=$(certbot renew --non-interactive 2>&1) && reload_out=$(reload 2>&1); then
      ping ok "$out"
    else
      ping fail "$out \${reload_out:-}"
      echo "$out" >&2
      exit 1
    fi
    ;;
  dry-run)
    certbot renew --dry-run --non-interactive
    ;;
  reload)
    reload
    ;;
  install)
    install -m 644 "$dir/cert-renew.service" "$dir/cert-renew.timer" /etc/systemd/system/
    systemctl daemon-reload
    systemctl enable --now cert-renew.timer
    ;;
  *)
    echo "usage: cert.sh issue|renew|dry-run|reload|install" >&2
    exit 2
    ;;
esac
`;
}

const service = `${HEADER}
[Unit]
Description=Renew the proxy certificate and reload nginx
After=docker.service
Requires=docker.service

[Service]
Type=oneshot
ExecStart=/bin/bash ${PROXY_DIR}/cert.sh renew
`;

const timer = `${HEADER}
[Unit]
Description=Renew the proxy certificate twice a day

[Timer]
OnCalendar=*-*-* 03,15:17:00 Asia/Seoul
RandomizedDelaySec=30min
Persistent=true

[Install]
WantedBy=timers.target
`;

/** Files to copy to PROXY_DIR: [{ path, content }]. Throws while no root domain exists (#539). */
export function renderProxy(data, { domain = data.platform.rootDomain } = {}) {
  if (!domain) throw new Error('platform.rootDomain is not set yet (#539). Pass --domain <name> to preview.');
  const apps = proxyApps(data, domain);
  return [
    { path: 'compose.yaml', content: compose(data.versions) },
    { path: 'nginx/apps.conf', content: nginxConf(domain, apps) },
    { path: 'cert.sh', content: certScript(domain) },
    { path: 'cert-renew.service', content: service },
    { path: 'cert-renew.timer', content: timer },
  ];
}
