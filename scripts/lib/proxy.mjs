// Builds the server reverse proxy from the registry (ADR-0012, #251): one nginx takes 443 for every
// active app and forwards to 127.0.0.1:<ports.web>, with one Let's Encrypt wildcard certificate that
// certbot renews through Route 53 DNS validation. The output is copied to PROXY_DIR on the server.
import { publicCheckScript, publicCheckService, publicCheckTimer } from './public-check.mjs';
import { signalsScript } from './signals.mjs';
import { serviceHost } from './registry.mjs';

export const PROXY_DIR = '/opt/project-standards/proxy';
export const SHARED_ENV = '/opt/project-standards/.env';

const HEADER = '# Generated by scripts/proxy-config.mjs in sirloinbh/project-standards from the registry. Do not edit it on the server; regenerate and copy it (docs/runbooks/proxy.md).';

/** Active apps and shared services (ADR-0015) with their address and web port, in slot order. */
export function proxyApps(data, domain) {
  const apps = data.projects.projects
    .filter((p) => p.status === 'active')
    .map((p) => {
      // The one wildcard certificate covers only names directly under the root domain.
      if (p.service.domain && p.service.domain !== domain) throw new Error(`${p.name}: service.domain "${p.service.domain}" is not covered by the *.${domain} certificate`);
      return { name: p.name, slot: p.slot, host: serviceHost(p, { rootDomain: domain }), port: p.ports.web, apiPort: p.ports.api, apiTimeoutSec: p.service.apiTimeoutSec, apiBodyMb: p.service.apiBodyMb, publicOrigin: p.service.publicOrigin };
    });
  const services = (data.projects.sharedServices ?? []).map((s) => ({ name: s.name, slot: s.slot, host: `${s.subdomain}.${domain}`, port: s.ports.web }));
  return [...apps, ...services].sort((a, b) => a.slot - b.slot);
}

// An app that sets service.apiTimeoutSec (#1114) or service.apiBodyMb (#1117) gets a `location /api/`; one that sets service.apiTimeoutSec waits that long for a slow /api/ call; every other
// path and every other app keeps nginx's 60 s default. A location with its own proxy_pass does not
// inherit the headers of `location /`, so they are written once here and used by both.
const proxyHeaders = (app) => `    proxy_pass http://127.0.0.1:${app.port};
    proxy_set_header Host $host;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto https;`;

// An app that sets service.apiBodyMb (#589, #1117) gets the same request body limit here as in its
// own nginx, so the host proxy's 1m default does not answer 413 first.
const apiLocation = (app) => {
  const limits = [
    app.apiBodyMb ? `    client_max_body_size ${app.apiBodyMb}m;` : '',
    app.apiTimeoutSec ? `    proxy_read_timeout ${app.apiTimeoutSec}s;\n    proxy_send_timeout ${app.apiTimeoutSec}s;` : '',
  ].filter(Boolean);
  return limits.length ? `\n  location /api/ {\n${proxyHeaders(app)}\n${limits.join('\n')}\n  }\n` : '';
};

// An app that sets service.publicOrigin gets its own TLS port that anyone may reach, for a webhook a
// third party calls (money-ledger's Kakao skill, money-ledger#314). The firewall opens that port to
// everyone, so only the one exact path and method is passed, straight to the app's API port
// (ports.api, published on 127.0.0.1 only); everything else is a 404.
const publicOriginServer = (app) => {
  const o = app.publicOrigin;
  return `# ${app.name} public origin (slot ${app.slot}): ${o.method} ${o.path} only
server {
  listen ${o.port} ssl;
  http2 on;
  server_name ${app.host};
  add_header Strict-Transport-Security "max-age=31536000" always;

  location = ${o.path} {
    limit_except ${o.method} { deny all; }
    client_max_body_size 16k;
${proxyHeaders({ ...app, port: app.apiPort })}
  }

  location / {
    return 404;
  }
}`;
};

/** The extra public ports of the apps that opt in (registry service.publicOrigin), checked and in port order. */
function publicOrigins(apps, data) {
  const origins = apps.filter((a) => a.publicOrigin);
  const taken = new Set(data.projects.projects.flatMap((p) => Object.values(p.ports)).concat((data.projects.sharedServices ?? []).flatMap((s) => Object.values(s.ports ?? {}))));
  for (const a of origins) if (taken.has(a.publicOrigin.port)) throw new Error(`${a.name}: service.publicOrigin.port ${a.publicOrigin.port} is already a registry port`);
  const seen = new Set();
  for (const a of origins) {
    if (seen.has(a.publicOrigin.port)) throw new Error(`service.publicOrigin.port ${a.publicOrigin.port} is used by two apps; give each app its own port`);
    seen.add(a.publicOrigin.port);
  }
  return origins.sort((a, b) => a.publicOrigin.port - b.publicOrigin.port);
}

function publicOriginSection(origins) {
  if (!origins.length) return '';
  const rejects = origins.map((a) => a.publicOrigin.port).map((port) => `server {
  listen ${port} ssl default_server;
  ssl_reject_handshake on;
}`);
  return `
# Extra public ports (service.publicOrigin). Unlike 80 and 443, these are open to everyone at the
# Lightsail firewall, so each serves one exact path and method of one app and nothing else; the app's
# API container is published on loopback only (ports.api), so this goes straight to it, not through
# the app's web nginx. Any other name gets no TLS handshake, as on 443.
${rejects.join('\n')}

${origins.map(publicOriginServer).join('\n\n')}
`;
}

function nginxConf(domain, apps, origins = []) {
  const server = (app) => `# ${app.name} (slot ${app.slot})
server {
  listen 443 ssl;
  http2 on;
  server_name ${app.host};
  # The app's own nginx sends nosniff and Referrer-Policy; HSTS belongs to the HTTPS layer.
  add_header Strict-Transport-Security "max-age=31536000" always;

  location / {
${proxyHeaders(app)}
  }
${apiLocation(app)}}`;
  return `${HEADER}
# Only allowed IPs reach 80 and 443 (Lightsail firewall, ADR-0012), so nginx has no allow list.
# The one exception is a service.publicOrigin port, open to everyone (see the end of this file).

ssl_certificate /etc/letsencrypt/live/${domain}/fullchain.pem;
ssl_certificate_key /etc/letsencrypt/live/${domain}/privkey.pem;
ssl_protocols TLSv1.2 TLSv1.3;
ssl_session_cache shared:SSL:10m;
ssl_session_timeout 1d;
server_tokens off;

# A name that is not an app gets nothing: no redirect, no certificate.
server {
  listen 80 default_server;
  return 444;
}
server {
  listen 443 ssl default_server;
  ssl_reject_handshake on;
}

server {
  listen 80;
  server_name ${apps.map((a) => a.host).join(' ')};
  return 301 https://$host$request_uri;
}

${apps.map(server).join('\n\n')}
${publicOriginSection(origins)}`;
}

function compose(versions) {
  return `${HEADER}
name: proxy
services:
  nginx:
    image: ${versions.images.nginx}
    # The apps publish their web ports on the host, so the proxy shares the host network.
    network_mode: host
    restart: unless-stopped
    volumes:
      - ./nginx/apps.conf:/etc/nginx/conf.d/default.conf:ro
      - ./letsencrypt:/etc/letsencrypt:ro
  certbot:
    image: ${versions.images.certbot}
    # Runs only from cert.sh, never with \`up\`.
    profiles: [certbot]
    # cert.sh exports these from CERTBOT_AWS_* in the shared server file.
    environment:
      - AWS_ACCESS_KEY_ID
      - AWS_SECRET_ACCESS_KEY
    volumes:
      - ./letsencrypt:/etc/letsencrypt
`;
}

function certScript(domain) {
  return `#!/usr/bin/env bash
${HEADER}
# Usage (as root):
#   cert.sh issue     first certificate for ${domain} and *.${domain}
#   cert.sh renew     renew when due, reload nginx, ping healthchecks.io (the timer runs this)
#   cert.sh dry-run   test renewal against the Let's Encrypt staging server
#   cert.sh reload    check and reload the nginx config after copying a new apps.conf
#   cert.sh install   install and start the twice-daily renewal timer
set -euo pipefail

dir=$(cd "$(dirname "$0")" && pwd)
shared_env=\${STANDARDS_ENV_FILE:-${SHARED_ENV}}
cd "$dir"

read_key() {
  [ -r "$shared_env" ] && sed -n "s/^$1=//p" "$shared_env" | tail -n 1 | tr -d "\\"'\\r"
}

certbot() {
  AWS_ACCESS_KEY_ID=$(read_key CERTBOT_AWS_ACCESS_KEY_ID || true)
  AWS_SECRET_ACCESS_KEY=$(read_key CERTBOT_AWS_SECRET_ACCESS_KEY || true)
  if [ -z "$AWS_ACCESS_KEY_ID" ] || [ -z "$AWS_SECRET_ACCESS_KEY" ]; then
    echo "CERTBOT_AWS_ACCESS_KEY_ID or CERTBOT_AWS_SECRET_ACCESS_KEY is missing in $shared_env" >&2
    return 1
  fi
  export AWS_ACCESS_KEY_ID AWS_SECRET_ACCESS_KEY
  docker compose run --rm certbot "$@"
}

reload() {
  docker compose exec -T nginx nginx -t
  docker compose exec -T nginx nginx -s reload
}

# Sends ok or fail to HEALTHCHECK_URL_CERT. A missing key or a failed ping never fails the caller.
ping() {
  local url
  url=$(read_key HEALTHCHECK_URL_CERT || true)
  [ -n "$url" ] || return 0
  [ "$1" = ok ] || url="$url/fail"
  printf '%s' "$2" | head -c 10000 | curl -fsS -m 10 --retry 3 -o /dev/null --data-binary @- "$url" || echo "healthchecks.io ping failed" >&2
}

case "\${1:-}" in
  issue)
    certbot certonly --dns-route53 --non-interactive --agree-tos --register-unsafely-without-email \\
      --cert-name ${domain} -d ${domain} -d '*.${domain}'
    ;;
  renew)
    if out=$(certbot renew --non-interactive 2>&1) && reload_out=$(reload 2>&1); then
      ping ok "$out"
    else
      ping fail "$out \${reload_out:-}"
      echo "$out" >&2
      exit 1
    fi
    ;;
  dry-run)
    certbot renew --dry-run --non-interactive
    ;;
  reload)
    reload
    ;;
  install)
    install -m 644 "$dir/cert-renew.service" "$dir/cert-renew.timer" /etc/systemd/system/
    systemctl daemon-reload
    systemctl enable --now cert-renew.timer
    ;;
  *)
    echo "usage: cert.sh issue|renew|dry-run|reload|install" >&2
    exit 2
    ;;
esac
`;
}

const service = `${HEADER}
[Unit]
Description=Renew the proxy certificate and reload nginx
After=docker.service
Requires=docker.service

[Service]
Type=oneshot
ExecStart=/bin/bash ${PROXY_DIR}/cert.sh renew
`;

const timer = `${HEADER}
[Unit]
Description=Renew the proxy certificate twice a day

[Timer]
OnCalendar=*-*-* 03,15:17:00 Asia/Seoul
RandomizedDelaySec=30min
Persistent=true

[Install]
WantedBy=timers.target
`;

/** Files to copy to PROXY_DIR: [{ path, content }]. Throws while no root domain exists (#539). */
export function renderProxy(data, { domain = data.platform.rootDomain } = {}) {
  if (!domain) throw new Error('platform.rootDomain is not set yet (#539). Pass --domain <name> to preview.');
  const apps = proxyApps(data, domain);
  const origins = publicOrigins(apps, data);
  return [
    { path: 'compose.yaml', content: compose(data.versions) },
    { path: 'nginx/apps.conf', content: nginxConf(domain, apps, origins) },
    { path: 'cert.sh', content: certScript(domain) },
    { path: 'cert-renew.service', content: service },
    { path: 'cert-renew.timer', content: timer },
    { path: 'public-check.sh', content: publicCheckScript(apps.map((a) => a.host), { sharedEnv: SHARED_ENV }) },
    { path: 'public-check.service', content: publicCheckService(PROXY_DIR) },
    { path: 'public-check.timer', content: publicCheckTimer() },
    { path: 'signals.sh', content: signalsScript(SHARED_ENV) },
  ];
}
