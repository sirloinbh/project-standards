// Builds the server-wide public URL probe (#1076, docs/research/uptime-gaps.md option A): every 5 minutes the server
// calls https://<host>/api/health of every active app and shared service through the host nginx (curl --resolve to
// 127.0.0.1, so the firewall does not matter), and once an hour also compares public DNS with the server address and
// checks the certificate lifetime. One signal summarises the result. The files go to PROXY_DIR next to cert.sh.
// proxy.mjs passes its two paths in, so the two modules do not import each other.

const HEADER = '# Generated by scripts/proxy-config.mjs in sirloinbh/project-standards from the registry. Do not edit it on the server; regenerate and copy it (docs/runbooks/proxy.md).';

/** The probe script for these hosts (strings such as "workout-memo.example.com"). */
export function publicCheckScript(hosts, { sharedEnv }) {
  return `#!/bin/bash
${HEADER}
# Public URL probe (#1076). Run by public-check.timer every 5 minutes.
#   public-check.sh          probe; DNS and certificate too in the first 5 minutes of each hour
#   public-check.sh quick    probe only
#   public-check.sh full     probe, DNS and certificate
#   public-check.sh install  install and start the timer
# Per host: GET https://<host>/api/health through the host nginx (curl --resolve to 127.0.0.1, 200, 10 s).
# Full: \`dig\` against a public resolver must return the server address, and the certificate must have 14 days left.
# Server .env keys (${sharedEnv}, all optional):
#   HEALTHCHECK_URL_PUBLIC     ping URL of the healthchecks.io check "public" (holds a secret UUID; never printed)
#   PUBLIC_CHECK_SERVER_IP     the server's public address; when empty it is read from checkip.amazonaws.com
#   PUBLIC_CHECK_RESOLVER      DNS server for the check (default 1.1.1.1)
#   PUBLIC_CHECK_DIG           name of the dig command (default dig; the tests point it at a missing name)
#   NOTIFY_SINK                where the result goes: healthchecks (default), aws or both. aws records the state for signals.sh,
#                              which sends the CloudWatch metrics and the SNS message (#1091)
# The signal body lists the failing host names and the reason, never a secret.
set -uo pipefail

dir=$(cd "$(dirname "$0")" && pwd)
shared_env=\${STANDARDS_ENV_FILE:-${sharedEnv}}
hosts=(${hosts.map((h) => `'${h}'`).join(' ')})

read_key() {
  [ -r "$shared_env" ] && sed -n "s/^$1=//p" "$shared_env" | tail -n 1 | tr -d "\\"'\\r"
}

# The only place that knows where the result goes. status is ok or fail. A missing key or a failed send never changes the exit code.
send_healthchecks() {
  local status=$1 body=$2 url
  url=$(read_key HEALTHCHECK_URL_PUBLIC || true)
  [ -n "$url" ] || return 0
  [ "$status" = ok ] || url="$url/fail"
  printf '%s' "$body" | head -c 10000 | curl -fsS -m 10 --retry 3 -o /dev/null --data-binary @- "$url" || echo "healthchecks.io ping failed" >&2
}

# The aws sink: record this signal, then judge all signals and send the metrics (this run is the 5-minute heartbeat).
send_aws() {
  local status=$1
  "\${SIGNALS_SH:-$dir/signals.sh}" record server public "$status" || echo "could not record the public signal" >&2
  "\${SIGNALS_SH:-$dir/signals.sh}" evaluate || echo "signals.sh evaluate failed" >&2
}

send_signal() {
  local status=$1 body=$2 sink
  sink=$(read_key NOTIFY_SINK || true)
  case "\${sink:-healthchecks}" in
    healthchecks) send_healthchecks "$status" "$body" ;;
    aws) send_aws "$status" ;;
    both)
      send_healthchecks "$status" "$body"
      send_aws "$status"
      ;;
    *) echo "unknown NOTIFY_SINK: $sink" >&2 ;;
  esac
  return 0
}

mode=\${1:-auto}
case "$mode" in
  install)
    install -m 644 "$dir/public-check.service" "$dir/public-check.timer" /etc/systemd/system/
    systemctl daemon-reload
    systemctl enable --now public-check.timer
    exit 0
    ;;
  quick | full) ;;
  auto) if [ "$(date +%-M)" -lt 5 ]; then mode=full; else mode=quick; fi ;;
  *)
    echo "usage: public-check.sh [quick|full|install]" >&2
    exit 2
    ;;
esac

failures=()
notes=()

server_ip=$(read_key PUBLIC_CHECK_SERVER_IP || true)
resolver=$(read_key PUBLIC_CHECK_RESOLVER || true)
resolver=\${resolver:-1.1.1.1}
dig_bin=$(read_key PUBLIC_CHECK_DIG || true)
dig_bin=\${dig_bin:-dig}
if [ "$mode" = full ]; then
  if [ -z "$server_ip" ]; then server_ip=$(curl -fsS -m 10 https://checkip.amazonaws.com 2> /dev/null | tr -d '[:space:]' || true); fi
  if [ -z "$server_ip" ]; then notes+=("dns skipped: server address unknown"); fi
  if ! command -v "$dig_bin" > /dev/null 2>&1; then notes+=("dns skipped: dig is not installed"); fi
fi

for host in "\${hosts[@]}"; do
  if ! curl -fsS -m 10 -o /dev/null --resolve "$host:443:127.0.0.1" "https://$host/api/health" 2> /dev/null; then
    failures+=("$host: https://$host/api/health did not answer 200 through nginx")
  fi
  [ "$mode" = full ] || continue
  if [ -n "$server_ip" ] && command -v "$dig_bin" > /dev/null 2>&1; then
    answers=$("$dig_bin" +short +time=3 +tries=1 A "$host" "@$resolver" 2> /dev/null || true)
    if ! printf '%s\\n' "$answers" | grep -Fxq "$server_ip"; then
      failures+=("$host: DNS from $resolver does not return the server address")
    fi
  fi
  # 14 days = 1209600 seconds. The wildcard certificate is the same for every host; each name is still checked once.
  if ! openssl s_client -connect 127.0.0.1:443 -servername "$host" < /dev/null 2> /dev/null | openssl x509 -noout -checkend 1209600 > /dev/null 2>&1; then
    failures+=("$host: certificate is missing or has fewer than 14 days left")
  fi
done

if [ "\${#failures[@]}" -eq 0 ]; then
  body="public ok: \${#hosts[@]} hosts ($mode)"
  if [ "\${#notes[@]}" -gt 0 ]; then body="$body; $(printf '%s; ' "\${notes[@]}")"; fi
  echo "$body"
  send_signal ok "$body"
else
  body="public fail ($mode): $(printf '%s; ' "\${failures[@]}")"
  echo "$body" >&2
  send_signal fail "$body"
  exit 1
fi
`;
}

export const publicCheckService = (proxyDir) => `${HEADER}
[Unit]
Description=Probe the public URLs of every app through the host nginx
After=docker.service
Wants=network-online.target

[Service]
Type=oneshot
ExecStart=/bin/bash ${proxyDir}/public-check.sh
TimeoutStartSec=3min
`;

export const publicCheckTimer = () => `${HEADER}
[Unit]
Description=Probe the public URLs every 5 minutes

[Timer]
OnCalendar=*:0/5
AccuracySec=30s
Persistent=false

[Install]
WantedBy=timers.target
`;
